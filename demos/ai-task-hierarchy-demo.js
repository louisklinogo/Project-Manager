/**
 * AI-Powered Task Hierarchy Demonstration
 *
 * This script demonstrates using the Gemini API to generate a task hierarchy
 * and then managing it with our task hierarchy implementation.
 *
 * It shows a real-world usage scenario with actual API calls.
 */

import { Task } from '../src/models/task.js';
import { TaskHierarchyManager } from '../src/utils/task-hierarchy-manager.js';
import { TaskHierarchyVisualizer } from '../src/utils/task-hierarchy-visualizer.js';
import { GeminiProvider } from '../src/providers/gemini-provider.js';
import dotenv from 'dotenv';

// Load environment variables
dotenv.config();

// Create a task hierarchy manager and visualizer
const manager = new TaskHierarchyManager();
const visualizer = new TaskHierarchyVisualizer({ format: 'markdown' });

// Initialize the Gemini provider
const geminiProvider = new GeminiProvider({
  apiKey: process.env.GEMINI_API_KEY
});

/**
 * Generate a task hierarchy using Gemini
 * @param {string} projectDescription - Description of the project
 * @returns {Promise<Array>} - Array of tasks
 */
async function generateTaskHierarchy(projectDescription) {
  console.log(`Generating task hierarchy for project: ${projectDescription}...\n`);

  const prompt = `
  Create a task hierarchy for the following project:

  ${projectDescription}

  Please provide a JSON array of tasks with the following structure:
  [
    {
      "id": "task-1",
      "title": "Main Task 1",
      "description": "Description of main task 1",
      "status": "pending",
      "priority": "high",
      "subtasks": [
        {
          "id": "subtask-1",
          "title": "Subtask 1",
          "description": "Description of subtask 1",
          "status": "pending",
          "priority": "medium"
        }
      ]
    }
  ]

  Include 3-5 main tasks with 2-3 subtasks each. Make sure each task has a unique ID, title, description, status (pending, in-progress, done), and priority (high, medium, low).

  IMPORTANT: Your response must be ONLY the JSON array, with no additional text, explanations, or markdown formatting.
  `;

  try {
    const response = await geminiProvider.generateChatCompletion({
      model: 'gemini-1.5-pro',
      messages: [
        { role: 'user', content: prompt }
      ],
      temperature: 0.2
    });

    // Extract the JSON from the response
    console.log('Raw response:', JSON.stringify(response, null, 2));

    // Handle different response formats from different providers
    let content = '';
    if (response.choices && response.choices[0] && response.choices[0].message) {
      // OpenAI format
      content = response.choices[0].message.content;
    } else if (response.candidates && response.candidates[0] && response.candidates[0].content) {
      // Gemini format
      content = response.candidates[0].content.parts[0].text;
    } else if (response.content) {
      // Simple format
      content = response.content;
    } else {
      console.log('Unexpected response format:', response);
      throw new Error('Unexpected response format');
    }

    console.log('Extracted content:', content);

    // Try to extract JSON from the content
    const jsonMatch = content.match(/\[\s*\{.*\}\s*\]/s);

    if (!jsonMatch) {
      console.log('Could not extract JSON pattern from content');
      // Try to parse the entire content as JSON
      try {
        return JSON.parse(content);
      } catch (e) {
        throw new Error('Could not extract JSON from response');
      }
    }

    const jsonString = jsonMatch[0];
    return JSON.parse(jsonString);
  } catch (error) {
    console.error('Error generating task hierarchy:', error);
    // Return a fallback task hierarchy
    return [
      {
        id: 'task-1',
        title: 'Fallback Task 1',
        description: 'This is a fallback task due to API error',
        status: 'pending',
        priority: 'high',
        subtasks: [
          {
            id: 'subtask-1',
            title: 'Fallback Subtask 1',
            description: 'This is a fallback subtask',
            status: 'pending',
            priority: 'medium'
          }
        ]
      }
    ];
  }
}

/**
 * Convert the generated tasks to Task objects
 * @param {Array} generatedTasks - Tasks generated by the AI
 * @returns {Array} - Array of Task objects
 */
function convertToTaskObjects(generatedTasks) {
  const tasks = [];

  for (const taskData of generatedTasks) {
    const subtasks = taskData.subtasks || [];
    delete taskData.subtasks;

    const task = new Task(taskData);

    // Add subtasks
    for (const subtaskData of subtasks) {
      subtaskData.parent_id = task.id;
      const subtask = new Task(subtaskData);
      task.subtasks.push(subtask);
    }

    tasks.push(task);
  }

  return tasks;
}

/**
 * Main function to run the demonstration
 */
async function runDemo() {
  console.log('AI-Powered Task Hierarchy Demonstration\n');

  // Generate a task hierarchy for a sample project
  const projectDescription = 'Create a mobile app for tracking personal fitness goals, including workout tracking, nutrition logging, and progress visualization.';

  try {
    // Generate tasks using Gemini
    const generatedTasks = await generateTaskHierarchy(projectDescription);
    console.log('Generated tasks from Gemini API:');
    console.log(JSON.stringify(generatedTasks, null, 2));

    // Convert to Task objects
    const tasks = convertToTaskObjects(generatedTasks);
    console.log('\nConverted to Task objects:');
    console.log(`Created ${tasks.length} main tasks with subtasks`);

    // Build the task hierarchy
    console.log('\nBuilding task hierarchy...');
    const hierarchy = manager.buildHierarchy(tasks);

    // Visualize the hierarchy
    console.log('\nTask Hierarchy:');
    console.log(visualizer.visualize(hierarchy));

    // Update task statuses based on subtasks
    console.log('\nUpdating task statuses based on subtasks...');
    const updatedTasks = manager.updateTaskStatuses(tasks);

    // Update task completion percentages
    console.log('Updating task completion percentages...');
    const tasksWithCompletion = manager.updateTaskCompletionPercentages(updatedTasks);

    // Visualize the updated hierarchy
    console.log('\nUpdated Task Hierarchy with Status and Completion:');
    const updatedHierarchy = manager.buildHierarchy(tasksWithCompletion);
    console.log(visualizer.visualize(updatedHierarchy));

    // Find tasks by criteria
    console.log('\nFinding high priority tasks...');
    const highPriorityTasks = manager.findTasks(tasksWithCompletion, { priority: 'high' });
    console.log(`Found ${highPriorityTasks.length} high priority tasks:`);
    highPriorityTasks.forEach(task => {
      console.log(`- ${task.title} (${task.status})`);
    });

    // Demonstrate task path
    if (tasks.length > 0 && tasks[0].subtasks.length > 0) {
      const subtask = tasks[0].subtasks[0];
      console.log(`\nTask path for "${subtask.title}":`);
      const path = manager.getTaskPathString(subtask, tasks);
      console.log(path);
    }

    console.log('\nAI-Powered Task Hierarchy Demonstration Complete!');
  } catch (error) {
    console.error('Error in demonstration:', error);
  }
}

// Run the demonstration
runDemo();
